// レンダラーに安全な API だけを公開する
const { contextBridge, ipcRenderer } = require('electron');

async function call(channel, arg) {
  const r = await ipcRenderer.invoke(channel, arg);
  if (!r.ok) throw new Error(r.error);
  return r.data;
}

contextBridge.exposeInMainWorld('api', {
  getBoard: () => call('board:get'),
  appInfo: () => call('app:info'),
  checkEnv: () => call('env:check'),
  chooseRepo: (opts) => call('repo:choose', opts || {}),
  openRepo: (dir) => call('repo:open', { path: dir }),
  browseDirs: (opts) => call('repo:browse', opts || {}),
  wslDistros: () => call('wsl:distros'),
  repoDefaultParent: (opts) => call('repo:defaultParent', opts || {}),
  chooseRepoParent: (opts) => call('repo:chooseParent', opts || {}),
  cloneRepo: (p) => call('repo:clone', p),
  createRepo: (p) => call('repo:create', p),
  repoInfo: () => call('repo:info'),
  updateSettings: (patch) => call('settings:update', patch),
  createCard: (p) => call('card:create', p),
  updateCard: (p) => call('card:update', p),
  createFromIssues: (p) => call('card:createFromIssues', p),
  createChat: (p) => call('chat:create', p),
  repoGithub: () => call('repo:github'),
  openExternal: (url) => call('open:external', url),
  ghStatus: () => call('gh:status'),
  ghInstall: () => call('gh:install'),
  ghLogin: () => call('gh:login'),
  ghAddProjectScope: () => call('gh:addProjectScope'),
  ghCancel: () => call('gh:cancel'),
  onGh: (cb) => ipcRenderer.on('gh:event', (_e, d) => cb(d)),
  start: (id) => call('card:start', id),
  resume: (id) => call('card:resume', id),
  resumeAll: () => call('card:resumeAll'),
  dismissInterrupted: (id) => call('card:dismissInterrupted', id),
  stop: (id) => call('card:stop', id),
  send: (id, message, skill, attachments) => call('card:send', { id, message, skill, attachments }),
  adoptCompetitor: (id) => call('compete:adopt', id),
  compareCompetitors: (id) => call('compete:compare', id),
  suggestSkills: (id) => call('card:suggestSkills', { id }),
  listSkills: () => call('skills:list'),
  readNotifications: (ids) => call('notifications:read', { ids }),
  clearNotifications: (ids) => call('notifications:clear', { ids }),
  actNotification: (id) => call('notifications:act', { id }),
  btw: (id, text) => call('card:btw', { id, text }),
  setSession: (id, session) => call('card:setSession', { id, session }),
  listSessions: () => call('sessions:list'),
  logs: (id) => call('card:logs', id),
  diff: (id) => call('card:diff', id),
  worktree: (id) => call('card:worktree', id),
  merge: (id, opts) => call('card:merge', { id, ...(opts || {}) }),
  createPr: (id, opts) => call('card:pr', { id, ...(opts || {}) }),
  discard: (id) => call('card:discard', id),
  resolveConflict: (id, mode) => call('conflict:resolve', { id, mode }),
  completeConflict: (id) => call('conflict:complete', id),
  abortConflict: (id) => call('conflict:abort', id),
  dismissConflict: (id) => call('conflict:dismiss', id),
  reopenPrConflict: (id) => call('conflict:fromPr', id),
  answerPermission: (id, reqId, decision, message) => call('card:permission', { id, reqId, decision, message }),
  answerQuestion: (id, reqId, answers) => call('card:answer', { id, reqId, answers }),
  open: (id) => call('card:open', id),
  onBoard: (cb) => ipcRenderer.on('board:changed', (_e, d) => cb(d)),
  onLog: (cb) => ipcRenderer.on('card:log', (_e, d) => cb(d)),
  onFocus: (cb) => ipcRenderer.on('card:focus', (_e, id) => cb(id)),
  remoteStatus: () => call('remote:status'),
  remoteHostInfo: () => call('remote:hostInfo'),
  remoteKeyStatus: (p) => call('remote:keyStatus', p || {}),
  remoteGenKey: (p) => call('remote:genKey', p || {}),
  remotePickPubKey: () => call('remote:pickPubKey'),
  remoteInstallPubKey: (p) => call('remote:installPubKey', p || {}),
  remoteStartHost: (p) => call('remote:startHost', p || {}),
  remoteStopHost: () => call('remote:stopHost'),
  remoteRefreshPair: () => call('remote:refreshPair'),
  remoteClearPairs: () => call('remote:clearPairs'),
  remoteConnect: (p) => call('remote:connect', p || {}),
  remoteResume: () => call('remote:resume'),
  remoteCancelResume: () => call('remote:cancelResume'),
  remoteDisconnect: () => call('remote:disconnect'),
  remoteForgetToken: () => call('remote:forgetToken'),
  onRemote: (cb) => ipcRenderer.on('remote:changed', (_e, d) => cb(d)),
});
